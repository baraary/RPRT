/**
 * Fast offline predictive generator based on current line/text
 */
export function getOfflineSmartSuggestions(
  currentText: string,
  modality: Modality,
  maxResults = 3
): string[] {
  if (!currentText || currentText.trim().length < 2) {
    return [
      'شواهدی از ضایعه فضاگیر یا تغییر پاتولوژیک بارز مشاهده نمی‌شود.',
      'ابعاد و اکوپترن در محدوده نرمال فیزیولوژیک قرار دارد.',
    ];
  }

  const lowerText = currentText.toLowerCase();
  const matchedSuggestions: { text: string; score: number }[] = [];

  for (const rule of MEDICAL_PREDICTION_RULES) {
    if (rule.modality && rule.modality !== 'all' && rule.modality !== modality) {
      continue;
    }

    let matchCount = 0;
    for (const kw of rule.keywords) {
      if (lowerText.includes(kw.toLowerCase())) {
        matchCount++;
      }
    }

    if (matchCount > 0) {
      for (const sug of rule.suggestions) {
        // Don't repeat if already in text
        if (!currentText.includes(sug.slice(0, 15))) {
          matchedSuggestions.push({
            text: sug,
            score: matchCount,
          });
        }
      }
    }
  }

  // Sort by match score
  matchedSuggestions.sort((a, b) => b.score - a.score);

  const unique = Array.from(new Set(matchedSuggestions.map((m) => m.text)));
  if (unique.length > 0) {
    return unique.slice(0, maxResults);
  }

  return [
    'یافته‌های تصویربرداری در حد نرمال فیزیولوژیک می‌باشد.',
    'شواهدی از لنفادنوپاتی یا مایع آزاد مشاهده نشد.',
    'تطابق بالینی پیشنهاد می‌گردد.',
  ];
}
